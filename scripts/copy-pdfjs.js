// Copies pdf.js (legacy build: polyfilled for older iOS WebKit), its worker, the standard fonts and
// the image decoders (JBIG2, JPEG 2000, color profiles) from node_modules into assets/pdfjs/, with
// the ".pdfasset" extension (metro.config.js), and writes the list in src/pdf/pdfjs-assets.ts.
// They ship inside the app: PDFs are drawn fully offline, nothing is ever fetched from a CDN.
// Run after updating pdfjs-dist:  npm run pdfjs:copy
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const source = path.join(root, 'node_modules', 'pdfjs-dist');
const target = path.join(root, 'assets', 'pdfjs');
const version = require(path.join(source, 'package.json')).version;

fs.rmSync(target, { recursive: true, force: true });
fs.mkdirSync(target, { recursive: true });

function copy(from, name) {
  fs.copyFileSync(from, path.join(target, `${name}.pdfasset`));
  return `require('@/assets/pdfjs/${name}.pdfasset')`;
}

const library = copy(path.join(source, 'legacy', 'build', 'pdf.min.mjs'), 'pdf');
const worker = copy(path.join(source, 'legacy', 'build', 'pdf.worker.min.mjs'), 'pdf.worker');
const fonts = fs
  .readdirSync(path.join(source, 'standard_fonts'))
  .filter((name) => /\.(pfb|ttf)$/.test(name))
  .map((name) => `  '${name}': ${copy(path.join(source, 'standard_fonts', name), name)},`);
const wasm = ['jbig2.wasm', 'openjpeg.wasm', 'qcms_bg.wasm'].map(
  (name) => `  '${name}': ${copy(path.join(source, 'wasm', name), name)},`,
);
for (const license of ['LICENSE']) fs.copyFileSync(path.join(source, license), path.join(target, 'LICENSE-pdfjs.txt'));

fs.writeFileSync(
  path.join(root, 'src', 'pdf', 'pdfjs-assets.ts'),
  `// Generated by scripts/copy-pdfjs.js (pdfjs-dist ${version}). Do not edit by hand.
/* eslint-disable @typescript-eslint/no-require-imports */
export const PDFJS_VERSION = '${version}';
export const PDFJS_LIBRARY: number = ${library};
export const PDFJS_WORKER: number = ${worker};
// Standard fonts and decoders, by the file name pdf.js asks for
export const PDFJS_FONTS: Record<string, number> = {
${fonts.join('\n')}
};
export const PDFJS_WASM: Record<string, number> = {
${wasm.join('\n')}
};
`,
);
console.log(`pdf.js ${version}: ${fonts.length} fonts, ${wasm.length} decoders → assets/pdfjs`);
